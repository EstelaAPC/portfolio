const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const languageButtons = document.querySelectorAll("[data-language]");
const languageGroup = document.querySelector(".language-switch");
const pageName = window.location.pathname.split("/").pop() || "index.html";

const applyLanguage = (language) => {
    const isEnglish = language === "en";
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let textNode;

    while ((textNode = walker.nextNode())) {
        if (!originalText.has(textNode)) {
            originalText.set(textNode, textNode.nodeValue);
        }

        const source = originalText.get(textNode);
        const trimmed = source.trim();
        const translated = isEnglish ? translations[trimmed] : trimmed;

        if (translated !== undefined) {
            textNode.nodeValue = source.replace(trimmed, translated);
        } else {
            textNode.nodeValue = source;
        }
    }

    document.querySelectorAll("[aria-label], [alt], [title], [placeholder], [data-tooltip]").forEach((element) => {
        for (const attribute of ["aria-label", "alt", "title", "placeholder", "data-tooltip"]) {
            if (!element.hasAttribute(attribute)) {
                continue;
            }

            let originals = originalAttributes.get(element);

            if (!originals) {
                originals = new Map();
                originalAttributes.set(element, originals);
            }

            if (!originals.has(attribute)) {
                originals.set(attribute, element.getAttribute(attribute));
            }

            const source = originals.get(attribute);
            element.setAttribute(attribute, isEnglish ? translations[source] || source : source);
        }
    });

    const metadata = pageCopy[pageName];

    document.documentElement.lang = isEnglish ? "en" : "pt-BR";
    document.title = isEnglish && metadata ? metadata.title : originalTextTitle;
    document.querySelector('meta[name="description"]').content = isEnglish && metadata
        ? metadata.description
        : originalDescription;

    languageGroup.setAttribute("aria-label", isEnglish ? "Language" : "Idioma");
    languageButtons.forEach((button) => {
        const isSelected = button.dataset.language === language;
        button.setAttribute("aria-pressed", String(isSelected));
    });

    const themeToggle = document.querySelector("[data-theme-toggle]");

    if (themeToggle) {
        const isDark = document.documentElement.dataset.theme === "dark";
        const label = isEnglish
            ? isDark ? "Switch to light mode" : "Switch to dark mode"
            : isDark ? "Ativar modo claro" : "Ativar modo escuro";

        themeToggle.setAttribute("aria-label", label);
        themeToggle.setAttribute("title", label);
    }
};

const originalTextTitle = document.title;
const descriptionMeta = document.querySelector('meta[name="description"]');
const originalDescription = descriptionMeta.content;
const savedLanguage = localStorage.getItem("portfolio-language");
applyLanguage(savedLanguage === "en" ? "en" : "pt");

languageButtons.forEach((button) => {
    button.addEventListener("click", () => {
        const language = button.dataset.language;
        localStorage.setItem("portfolio-language", language);
        applyLanguage(language);
        document.dispatchEvent(new CustomEvent("portfolio:languagechange", { detail: { language } }));
    });
});
